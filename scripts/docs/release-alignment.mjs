const errors=[];
for(const dir of ['','hardhat/','ui/']){
 const pkg=json(dir+'package.json'),lock=json(dir+'package-lock.json');
 if(pkg.version!==version||lock.version!==version||lock.packages?.['']?.version!==version)errors.push(`Package/lock version mismatch: ${dir||'root'}`);
}
if(json('config/usdc-deployment.json').version!==version)errors.push('Deployment registry software version differs');
const scripts=json('hardhat/package.json').scripts;
for(const [,name] of commands){
 if(!scripts[name]){errors.push(`Missing Hardhat command: ${name}`);continue;}
 for(const m of scripts[name].matchAll(/(?:run|node)\s+(scripts\/[\w./-]+\.[cm]?js)\b/g))if(!fs.existsSync(path.join(root,'hardhat',m[1])))errors.push(`Missing executable for ${name}: ${m[1]}`);
}
const files=['README.md','hardhat/README.md','ui/README.md'];
function collect(dir){for(const e of fs.readdirSync(path.join(root,dir),{withFileTypes:true})){
 const p=dir+'/'+e.name;
 if(e.isDirectory()){if(!['releases','qualification','LEGAL','security'].includes(e.name))collect(p);}
 else if(e.isFile()&&e.name.endsWith('.md'))files.push(p);
}}
collect('docs');
for(const file of files){
 const text=read(file),heading=text.split('\n')[0];
 if(!/superseded/i.test(heading))for(const m of heading.matchAll(/\bv?(\d+\.\d+(?:\.\d+)?)\b/g))if(m[1]!==version)errors.push(`Stale active guide heading: ${file}`);
 for(const m of text.matchAll(/https:\/\/github\.com\/MontrealAI\/AGIJobManager\/releases\/download\/v(\d+\.\d+\.\d+)\//g))if(m[1]!==version)errors.push(`Old download in active guide: ${file}`);
}
const consoleHTML=read('ui/agijobmanager-usdc.html');
if(!consoleHTML.match(/<title>([^<]+)<\/title>/)?.[1].includes(tag))errors.push('Standalone console title version differs');
const dest='docs/RELEASE_GUIDE.md';
if(process.argv.includes('--write'))fs.writeFileSync(path.join(root,dest),generated);
else if(!fs.existsSync(path.join(root,dest))||read(dest)!==generated)errors.push('Generated release guide is stale; run npm run docs:gen');
if(errors.length){for(const e of errors)console.error(e);process.exitCode=1;}
else console.log(`Release alignment passed: ${tag}, ${files.length} active guides, ${commands.length} deployment commands.`);
