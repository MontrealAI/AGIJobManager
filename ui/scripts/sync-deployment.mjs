import fs from 'node:fs';
import path from 'node:path';

const repoRoot = path.resolve(process.cwd(), '..');
const deploymentPath = path.join(repoRoot, 'hardhat/deployments/mainnet/deployment.1.24522684.json');
const solcInputPath = path.join(repoRoot, 'hardhat/deployments/mainnet/solc-input.json');
const outputPath = path.join(repoRoot, 'ui/src/generated/deployment.ts');

const deployment = JSON.parse(fs.readFileSync(deploymentPath, 'utf8'));
const solcInput = JSON.parse(fs.readFileSync(solcInputPath, 'utf8'));

const deploymentConstant = {
  releaseTag: 'v0.1.0-mainnet-beta',
  releaseUrl: 'https://github.com/MontrealAI/AGIJobManager/releases/tag/v0.1.0-mainnet-beta',
  chainId: deployment.chainId,
  explorerBaseUrl: deployment.explorerBaseUrl,
  deployer: deployment.deployer,
  finalOwner: deployment.finalOwner,
  deploymentBlock: deployment.contracts.AGIJobManager.blockNumber,
  addresses: Object.fromEntries(Object.entries(deployment.contracts).map(([name, data]) => [name, data.address])),
  constructorArgs: deployment.constructorArgs,
  compiler: {
    version: '0.8.23',
    optimizerEnabled: Boolean(solcInput.settings.optimizer?.enabled),
    optimizerRuns: Number(solcInput.settings.optimizer?.runs ?? 0),
    evmVersion: solcInput.settings.evmVersion,
    viaIR: Boolean(solcInput.settings.viaIR),
    metadataBytecodeHash: solcInput.settings.metadata?.bytecodeHash,
    revertStrings: solcInput.settings.debug?.revertStrings
  }
};

const header = `// AUTO-GENERATED FILE. DO NOT EDIT.\n// Generated by: ui/scripts/sync-deployment.mjs\n`;
const body = `export const OFFICIAL_DEPLOYMENT = ${JSON.stringify(deploymentConstant, null, 2)} as const;\n`;

fs.writeFileSync(outputPath, `${header}\n${body}`);
console.log(`Wrote ${path.relative(repoRoot, outputPath)}`);
